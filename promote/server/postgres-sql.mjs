// Translate server-owned SQLite statements without interpolating values.
export const tables = new Set(['settings','tenants','users','memberships','sessions','invitations','services','events','bookings','orders','tickets','proofs','plans','invoices','subscriptions','notices','push_jobs','activity','metrics','limits','domains','assets','sponsor_campaigns','sponsor_activity','professional_profiles','professional_work','music_tracks','event_plans','delivery_assets','client_deliveries','file_objects','upload_intents','file_imports']);
export function postgresSql(input) {
  let index=0;
  const literals=[];
  let sql=input.replace(/'(?:''|[^'])*'|"(?:[^"]|"")*"|--[^\n]*|\/\*[\s\S]*?\*\//g, literal=>'\x01'+(literals.push(literal)-1)+'\x02');
  sql=sql.replace(/\?/g,()=>'$'+(++index));
  const ignore=/^\s*INSERT OR IGNORE\b/i.test(sql);
  sql=sql.replace(/^\s*INSERT OR IGNORE\b/i,'INSERT');
  sql=sql.replace(/\b(FROM|JOIN|UPDATE|INTO)\s+([a-z_][a-z_0-9]*)\b/gi,(match,keyword,table)=>tables.has(table)?keyword+' promote.'+table:match);
  sql=sql.replace(/\bAS\s+([a-z][a-z_0-9]*)\b/gi,(_,alias)=>'AS "'+alias+'"');
  sql=sql.replace(/\x01(\d+)\x02/g,(_,i)=>literals[Number(i)]);
  sql=sql.replace(/json_extract\(payload,'\$\.publicEnabled'\)/g,"CASE WHEN payload::jsonb ? 'publicEnabled' THEN CASE WHEN (payload::jsonb->>'publicEnabled')::boolean THEN 1 ELSE 0 END ELSE NULL END");
  if(ignore)sql=sql.replace(/;?\s*$/,' ON CONFLICT DO NOTHING');
  return sql;
}
export function postgresSchema(sqlite) {
  return 'BEGIN; CREATE SCHEMA IF NOT EXISTS promote; SET LOCAL search_path=promote,pg_catalog;\n'+sqlite.replace(/PRAGMA[^;]+;/g,'').replace(/INTEGER PRIMARY KEY AUTOINCREMENT/g,'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY').replace(/ UNIQUE COLLATE NOCASE/g,' UNIQUE').replace(/resets_at INTEGER/g,'resets_at BIGINT')+
String.raw`
CREATE TABLE IF NOT EXISTS file_objects(path TEXT PRIMARY KEY,tenant_id TEXT REFERENCES tenants(id),bucket TEXT NOT NULL,mime TEXT NOT NULL,size BIGINT NOT NULL CHECK(size>=0),created_at TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS file_objects_tenant ON file_objects(tenant_id);
CREATE TABLE IF NOT EXISTS upload_intents(id TEXT PRIMARY KEY,tenant_id TEXT NOT NULL REFERENCES tenants(id),target TEXT NOT NULL,owner TEXT NOT NULL,doc TEXT NOT NULL,state TEXT NOT NULL,reserved BIGINT NOT NULL CHECK(reserved>=0),expires_at TEXT NOT NULL,cleanup_at TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS upload_intents_expiry ON upload_intents(cleanup_at);
CREATE INDEX IF NOT EXISTS upload_intents_tenant ON upload_intents(tenant_id);
CREATE TABLE IF NOT EXISTS file_imports(path TEXT PRIMARY KEY,tenant_id TEXT REFERENCES tenants(id),bucket TEXT NOT NULL,mime TEXT NOT NULL,body TEXT NOT NULL,sha256 TEXT NOT NULL,created_at TEXT NOT NULL);
DO $security$ DECLARE item record; BEGIN
 FOR item IN SELECT tablename FROM pg_tables WHERE schemaname='promote' LOOP
  EXECUTE format('ALTER TABLE promote.%I ENABLE ROW LEVEL SECURITY',item.tablename);
 END LOOP;
END $security$;
REVOKE ALL ON SCHEMA promote FROM PUBLIC,anon,authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA promote FROM PUBLIC,anon,authenticated;
COMMIT;
`;
}
